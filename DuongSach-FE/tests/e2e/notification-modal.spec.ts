import { expect, test } from '@playwright/test';
test('notification modals handle cancel, confirm, input, focus and queued notices', async ({ page }) => {
  let nativeDialogs = 0;
  page.on('dialog', async dialog => { nativeDialogs++; await dialog.dismiss(); });
  await page.route('**/modal-test', route => route.fulfill({ contentType: 'text/html', body: '<html lang="vi"><head><meta name="viewport" content="width=device-width, initial-scale=1.0"><script type="module">import RefreshRuntime from "/@react-refresh"; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;</script><script type="module" src="/@vite/client"></script></head><body><div id="root"></div><script type="module" src="/tests/e2e/fixtures/notification-modal.tsx"></script></body></html>' }));
  await page.goto('/modal-test');
  const dialog = page.getByRole('dialog');
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Hủy', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.locator('output')).toHaveText('false');
  await expect(page.getByRole('button', { name: 'Delete', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await dialog.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.locator('output')).toHaveText('true');
  await page.getByRole('button', { name: 'Input', exact: true }).click();
  await expect(dialog.getByRole('textbox')).toHaveValue('Nội dung cũ');
  await dialog.getByRole('textbox').fill('Lý do mới');
  await dialog.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.locator('output')).toHaveText('Lý do mới');
  await page.getByRole('button', { name: 'Notices', exact: true }).click();
  await expect(dialog).toContainText('Thông báo thứ nhất');
  await dialog.getByRole('button', { name: 'Đã hiểu', exact: true }).click();
  await expect(dialog).toContainText('Thông báo thứ hai');
  const box = await dialog.boundingBox();
  expect(box!.width).toBeLessThanOrEqual(page.viewportSize()!.width);
  await dialog.getByRole('button', { name: 'Đã hiểu', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(nativeDialogs).toBe(0);
});
